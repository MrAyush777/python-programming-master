# to know the type of variable we can use type() operator

a = 4
b = False

print(type(a))
print(type(b))

# if we want to change the type of variable than we can ... yes , its possible using 'variable operator' 
# means like use variable type as operator name like this :
# int() , float() , str() , etc

a = "32.4"
print(type(a))
print(a)
b = float(a)
print(type(b))
print(b)
